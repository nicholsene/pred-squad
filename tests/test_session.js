assert(Math.abs(h[0]-100)<1e-6 && Math.abs(h[4]-50)<1e-6 && Math.abs(h[2]-10)<1e-6);
assert.throws(()=>P.mapping([{x:0,y:0},{x:0,y:0},{x:0,y:0},{x:0,y:0}]));
console.log("ok: perspective mapping and degenerate corner rejection");
